AOpenWorldCharacter::AOpenWorldCharacter()
{
	// Set size for collision capsule
	GetCapsuleComponent()->InitCapsuleSize(42.f, 96.0f);
		
	// Don't rotate when the controller rotates. Let that just affect the camera.
	bUseControllerRotationPitch = false;
	bUseControllerRotationYaw = false;
	bUseControllerRotationRoll = false;

	// Configure character movement
	GetCharacterMovement()->bOrientRotationToMovement = true;
	GetCharacterMovement()->RotationRate = FRotator(0.0f, 500.0f, 0.0f);

	// Note: For faster iteration times these variables, and many more, can be tweaked in the Character Blueprint
	// instead of recompiling to adjust them
	GetCharacterMovement()->JumpZVelocity = 500.f;
	GetCharacterMovement()->AirControl = 0.35f;
	GetCharacterMovement()->MaxWalkSpeed = 500.f;
	GetCharacterMovement()->MinAnalogWalkSpeed = 20.f;
	GetCharacterMovement()->BrakingDecelerationWalking = 2000.f;
	GetCharacterMovement()->BrakingDecelerationFalling = 1500.0f;

	// Create a camera boom (pulls in towards the player if there is a collision)
	CameraBoom = CreateDefaultSubobject<USpringArmComponent>(TEXT("CameraBoom"));
	CameraBoom->SetupAttachment(RootComponent);
	CameraBoom->TargetArmLength = 400.0f;
	CameraBoom->bUsePawnControlRotation = true;

	// Create a follow camera
	FollowCamera = CreateDefaultSubobject<UCameraComponent>(TEXT("FollowCamera"));
	FollowCamera->SetupAttachment(CameraBoom, USpringArmComponent::SocketName);
	FollowCamera->bUsePawnControlRotation = false;

	// Note: The skeletal mesh and anim blueprint references on the Mesh component (inherited from Character)
	// are set in the derived blueprint asset named ThirdPersonCharacter (to avoid direct content references in C++)

	// Needed for smooth zoom and "both buttons = walk forward"
	PrimaryActorTick.bCanEverTick = true;

	// Weapon in the right hand and shield in the left. The meshes are built (Tools/create_weapons.py)
	// so that their grips sit in the HandGrip_R / HandGrip_L sockets of the mannequin.
	const auto CreateHeldMesh = [this](const TCHAR* Name, FName Socket)
	{
		UStaticMeshComponent* Held = CreateDefaultSubobject<UStaticMeshComponent>(Name);
		Held->SetupAttachment(GetMesh(), Socket);
		Held->SetCollisionEnabled(ECollisionEnabled::NoCollision);
		Held->SetGenerateOverlapEvents(false);
		Held->CanCharacterStepUpOn = ECB_No;
		return Held;
	};
	Weapon = CreateHeldMesh(TEXT("Weapon"), WeaponSocketName);
	OffHandWeapon = CreateHeldMesh(TEXT("OffHandWeapon"), OffHandSocketName);

	// Default loadouts; meshes and animations are generated by the scripts in Tools/.
	// HitTime / ComboTime match hit_time / combo_time in Tools/create_attack_anims.py.
	static ConstructorHelpers::FObjectFinder<UStaticMesh> SwordMesh(TEXT("/Game/Weapons/Sword/SM_Sword.SM_Sword"));
	static ConstructorHelpers::FObjectFinder<UStaticMesh> ShieldMesh(TEXT("/Game/Weapons/Shield/SM_Shield.SM_Shield"));
	static ConstructorHelpers::FObjectFinder<UStaticMesh> GreatswordMesh(TEXT("/Game/Weapons/Greatsword/SM_Greatsword.SM_Greatsword"));
	static ConstructorHelpers::FObjectFinder<UAnimSequence> SwordStance(TEXT("/Game/Weapons/Sword/Anims/AS_Stance_SwordShield.AS_Stance_SwordShield"));
	static ConstructorHelpers::FObjectFinder<UAnimSequence> GreatswordStance(TEXT("/Game/Weapons/Greatsword/Anims/AS_Stance_Greatsword.AS_Stance_Greatsword"));
	static ConstructorHelpers::FObjectFinder<UAnimSequence> SwordSlash(TEXT("/Game/Weapons/Sword/Anims/AS_SwordSlash.AS_SwordSlash"));
	static ConstructorHelpers::FObjectFinder<UAnimSequence> GreatswordSlash(TEXT("/Game/Weapons/Greatsword/Anims/AS_GreatswordSlash.AS_GreatswordSlash"));

	FOpenWorldLoadout& SwordAndShield = Loadouts.AddDefaulted_GetRef();
	SwordAndShield.DisplayName = FText::FromString(TEXT("Sword and shield"));
	SwordAndShield.MainHandMesh = SwordMesh.Object;
	SwordAndShield.OffHandMesh = ShieldMesh.Object;
	SwordAndShield.StanceAnimation = SwordStance.Object;
	SwordAndShield.AttackAnimation = SwordSlash.Object;
	SwordAndShield.HitTime = 0.38f;
	SwordAndShield.ComboTime = 0.66f;
	SwordAndShield.TraceDistance = 110.f;

	FOpenWorldLoadout& TwoHanded = Loadouts.AddDefaulted_GetRef();
	TwoHanded.DisplayName = FText::FromString(TEXT("Two-handed sword"));
	TwoHanded.MainHandMesh = GreatswordMesh.Object;
	TwoHanded.StanceAnimation = GreatswordStance.Object;
	TwoHanded.AttackAnimation = GreatswordSlash.Object;
	TwoHanded.HitTime = 0.47f;
	TwoHanded.ComboTime = 0.84f;
	TwoHanded.TraceDistance = 140.f;
	TwoHanded.TraceRadius = 50.f;
	TwoHanded.Damage = 2.f;
	TwoHanded.KnockbackImpulse = 400.f;

	// Shown in the Blueprint editor; BeginPlay equips the starting loadout
	Weapon->SetStaticMesh(SwordMesh.Object);
	OffHandWeapon->SetStaticMesh(ShieldMesh.Object);
}

void AOpenWorldCharacter::BeginPlay()
{
	Super::BeginPlay();

	DefaultRotationRateYaw = GetCharacterMovement()->RotationRate.Yaw;
	DefaultWalkSpeed = GetCharacterMovement()->MaxWalkSpeed;

	// Re-attach in case the socket names were changed in the Blueprint
	Weapon->AttachToComponent(GetMesh(), FAttachmentTransformRules::KeepRelativeTransform, WeaponSocketName);
	OffHandWeapon->AttachToComponent(GetMesh(), FAttachmentTransformRules::KeepRelativeTransform, OffHandSocketName);

	EquipLoadout(Loadouts.IsValidIndex(StartingLoadoutIndex) ? StartingLoadoutIndex : 0);

	// Start from the arm length set in the Blueprint, within the zoom limits
	SetZoomDistance(CameraBoom->TargetArmLength, true);

#if !UE_BUILD_SHIPPING
	bSelfTest = FParse::Param(FCommandLine::Get(), TEXT("OWSelfTest"));
	if (bSelfTest)
	{
		// Without a renderer the pose is not evaluated unless asked to. Ask from the very first frame,
		// so the test also covers the blend into the starting stance.
		GetMesh()->VisibilityBasedAnimTickOption = EVisibilityBasedAnimTickOption::AlwaysTickPoseAndRefreshBones;
	}
#endif
}

void AOpenWorldCharacter::Tick(float DeltaSeconds)
{
	Super::Tick(DeltaSeconds);

	// Smooth zoom
	if (!FMath::IsNearlyEqual(CameraBoom->TargetArmLength, TargetZoomDistance, 0.1f))
	{
		CameraBoom->TargetArmLength = ZoomInterpSpeed > 0.f
			? FMath::FInterpTo(CameraBoom->TargetArmLength, TargetZoomDistance, DeltaSeconds, ZoomInterpSpeed)
			: TargetZoomDistance;
	}

	// Both mouse buttons held: walk forward in the camera direction
	if (bBothButtonsMoveForward && bCameraRotating && bCameraOrbiting)
	{
		DoMove(0.f, 1.f);
	}

	UpdateAttack();

#if !UE_BUILD_SHIPPING
	if (bSelfTest)
	{
		TickSelfTest(DeltaSeconds);
	}
#endif
}

void AOpenWorldCharacter::SetZoomDistance(float Distance, bool bInstant)
{
	TargetZoomDistance = FMath::Clamp(Distance, MinZoomDistance, FMath::Max(MinZoomDistance, MaxZoomDistance));

	if (bInstant)
	{
		CameraBoom->TargetArmLength = TargetZoomDistance;
	}
}

void AOpenWorldCharacter::SetupCameraInput()
{
	// Create default camera actions so the project works without extra input assets.
	// Any of these can be replaced by real assets in the character Blueprint.
	if (!CameraZoomAction)
	{
		CameraZoomAction = NewObject<UInputAction>(this, TEXT("IA_CameraZoom_Runtime"));
		CameraZoomAction->ValueType = EInputActionValueType::Axis1D;
	}

	if (!CameraRotateAction)
	{
		CameraRotateAction = NewObject<UInputAction>(this, TEXT("IA_CameraRotate_Runtime"));
		CameraRotateAction->ValueType = EInputActionValueType::Boolean;
	}

	if (!CameraOrbitAction)
	{
		CameraOrbitAction = NewObject<UInputAction>(this, TEXT("IA_CameraOrbit_Runtime"));
		CameraOrbitAction->ValueType = EInputActionValueType::Boolean;
	}

	if (!SprintAction)
	{
		SprintAction = NewObject<UInputAction>(this, TEXT("IA_Sprint_Runtime"));
		SprintAction->ValueType = EInputActionValueType::Boolean;
	}

	if (!SwitchLoadoutAction)
	{
		SwitchLoadoutAction = NewObject<UInputAction>(this, TEXT("IA_SwitchLoadout_Runtime"));
		SwitchLoadoutAction->ValueType = EInputActionValueType::Boolean;
	}

	if (!CameraMappingContext)
	{
		CameraMappingContext = NewObject<UInputMappingContext>(this, TEXT("IMC_Camera_Runtime"));
		CameraMappingContext->MapKey(CameraZoomAction, EKeys::MouseWheelAxis);
		CameraMappingContext->MapKey(CameraRotateAction, EKeys::RightMouseButton);
		CameraMappingContext->MapKey(CameraOrbitAction, EKeys::LeftMouseButton);
		CameraMappingContext->MapKey(SprintAction, EKeys::LeftShift);
		// Turning the wheel zooms the camera; clicking it switches the loadout
		CameraMappingContext->MapKey(SwitchLoadoutAction, EKeys::MiddleMouseButton);
	}

	if (const APlayerController* PC = Cast<APlayerController>(GetController()))
	{
		if (UEnhancedInputLocalPlayerSubsystem* Subsystem = ULocalPlayer::GetSubsystem<UEnhancedInputLocalPlayerSubsystem>(PC->GetLocalPlayer()))
		{
			if (!Subsystem->HasMappingContext(CameraMappingContext))
			{
				Subsystem->AddMappingContext(CameraMappingContext, CameraMappingPriority);
			}
		}
	}
}

void AOpenWorldCharacter::MouseLook(const FInputActionValue& Value)
{
	// The mouse only moves the camera while a camera button is held; otherwise it moves the cursor
	if (IsCameraControlActive())
	{
		if (bCameraOrbiting)
		{
			// Track how far the mouse moved, to tell a click from a camera drag
			const FVector2D Delta = Value.Get<FVector2D>();
			OrbitMouseTravel += FMath::Abs(Delta.X) + FMath::Abs(Delta.Y);
		}

		Look(Value);
	}
}

void AOpenWorldCharacter::CameraZoom(const FInputActionValue& Value)
{
	// Wheel up (positive) zooms in
	SetZoomDistance(TargetZoomDistance - Value.Get<float>() * ZoomStep);
}

void AOpenWorldCharacter::CameraRotateStarted()
{
	bCameraRotating = true;
	UpdateRotationMode();
}

void AOpenWorldCharacter::CameraRotateCompleted()
{
	bCameraRotating = false;
	UpdateRotationMode();
}

void AOpenWorldCharacter::CameraOrbitStarted()
{
	bCameraOrbiting = true;
	OrbitPressTime = GetWorld()->GetTimeSeconds();
	OrbitMouseTravel = 0.f;
	UpdateRotationMode();
}

void AOpenWorldCharacter::CameraOrbitCompleted()
{
	bCameraOrbiting = false;
	UpdateRotationMode();

	// A short left click without dragging the camera is an attack
	const float HeldTime = GetWorld()->GetTimeSeconds() - OrbitPressTime;
	if (HeldTime <= AttackClickMaxDuration && OrbitMouseTravel <= AttackClickMaxMouseTravel)
	{
		Attack();
	}
}

void AOpenWorldCharacter::SprintStarted()
{
	GetCharacterMovement()->MaxWalkSpeed = SprintSpeed;
}

void AOpenWorldCharacter::SprintCompleted()
{
	GetCharacterMovement()->MaxWalkSpeed = DefaultWalkSpeed;
}

UOpenWorldAnimInstance* AOpenWorldCharacter::GetOverlayAnimInstance() const
{
	return Cast<UOpenWorldAnimInstance>(GetMesh()->GetAnimInstance());
}

void AOpenWorldCharacter::EquipLoadout(int32 Index)
{
	if (!Loadouts.IsValidIndex(Index))
	{
		return;
	}

	CurrentLoadoutIndex = Index;
	const FOpenWorldLoadout& Loadout = Loadouts[Index];
	Weapon->SetStaticMesh(Loadout.MainHandMesh);
	OffHandWeapon->SetStaticMesh(Loadout.OffHandMesh);

	// The arms carry this equipment in its own pose, clear of the body, in every locomotion state
	if (UOpenWorldAnimInstance* AnimInstance = GetOverlayAnimInstance())
	{
		AnimInstance->SetStance(Loadout.StanceAnimation);
	}
}

void AOpenWorldCharacter::EquipNextLoadout()
{
	// Weapons are not swapped in the middle of a swing
	if (bIsAttacking || Loadouts.Num() == 0)
	{
		return;
	}

	EquipLoadout((FMath::Max(CurrentLoadoutIndex, 0) + 1) % Loadouts.Num());
}

void AOpenWorldCharacter::Attack()
{
	if (bIsAttacking)
	{
		// Remember the click; UpdateAttack chains the next attack once the combo window opens
		CachedAttackInputTime = GetWorld()->GetTimeSeconds();
		return;
	}

	StartAttack();
}

void AOpenWorldCharacter::StartAttack()
{
	UOpenWorldAnimInstance* AnimInstance = GetOverlayAnimInstance();
	if (!AnimInstance)
	{
		UE_LOG(LogOpenWorld, Warning, TEXT("'%s' can not attack: its Anim Blueprint is not based on OpenWorldAnimInstance."), *GetNameSafe(this));
		return;
	}

	if (!Loadouts.IsValidIndex(CurrentLoadoutIndex) || !Loadouts[CurrentLoadoutIndex].AttackAnimation)
	{
		UE_LOG(LogOpenWorld, Warning, TEXT("'%s' has no attack animation in the current loadout."), *GetNameSafe(this));
		return;
	}

	// Standing still: swing where the camera looks. While running the character keeps its heading.
	if (bFaceCameraOnAttack && GetController() && GetVelocity().SizeSquared2D() < FMath::Square(20.f))
	{
		SetActorRotation(FRotator(0.f, GetController()->GetControlRotation().Yaw, 0.f));
	}

	AnimInstance->PlayOverlay(Loadouts[CurrentLoadoutIndex].AttackAnimation);
	bIsAttacking = true;
	bHitChecked = false;
	CachedAttackInputTime = -1000.f;
}

void AOpenWorldCharacter::UpdateAttack()
{
	if (!bIsAttacking)
	{
		return;
	}

	const UOpenWorldAnimInstance* AnimInstance = GetOverlayAnimInstance();
	const bool bClickQueued = GetWorld()->GetTimeSeconds() - CachedAttackInputTime <= ComboInputCacheTime;

	if (!AnimInstance || !AnimInstance->IsOverlayPlaying() || !Loadouts.IsValidIndex(CurrentLoadoutIndex))
	{
		// The animation ran to its end
		bIsAttacking = false;
		if (bClickQueued)
		{
			StartAttack();
		}
		return;
	}

	const FOpenWorldLoadout& Loadout = Loadouts[CurrentLoadoutIndex];
	const float Time = AnimInstance->GetOverlayTime();

	if (!bHitChecked && Time >= Loadout.HitTime)
	{
		bHitChecked = true;
		DoAttackTrace(Loadout);
	}

	// Past the cut: a queued click starts the next attack without waiting for the recovery
	if (bClickQueued && Time >= Loadout.ComboTime)
	{
		StartAttack();
	}
}

void AOpenWorldCharacter::DoAttackTrace(const FOpenWorldLoadout& Loadout)
{
	// Sweep forward from the character's chest, covering the weapon's reach
	const FVector TraceStart = GetActorLocation();
	const FVector TraceEnd = TraceStart + GetActorForwardVector() * Loadout.TraceDistance;

	FCollisionObjectQueryParams ObjectParams;
	ObjectParams.AddObjectTypesToQuery(ECC_Pawn);
	ObjectParams.AddObjectTypesToQuery(ECC_WorldDynamic);

	FCollisionQueryParams QueryParams(SCENE_QUERY_STAT(OpenWorldMeleeTrace), false, this);

	TArray<FHitResult> Hits;
	if (!GetWorld()->SweepMultiByObjectType(Hits, TraceStart, TraceEnd, FQuat::Identity, ObjectParams,
		FCollisionShape::MakeSphere(Loadout.TraceRadius), QueryParams))
	{
		return;
	}

	TSet<AActor*> AlreadyHit;
	for (const FHitResult& Hit : Hits)
	{
		AActor* HitActor = Hit.GetActor();
		if (!HitActor || AlreadyHit.Contains(HitActor))
		{
			continue;
		}
		AlreadyHit.Add(HitActor);

		const FVector Impulse = GetActorForwardVector() * Loadout.KnockbackImpulse;

		if (ICombatDamageable* Damageable = Cast<ICombatDamageable>(HitActor))
		{
			Damageable->ApplyDamage(Loadout.Damage, this, Hit.ImpactPoint, Impulse);
		}
		else if (UPrimitiveComponent* HitComponent = Hit.GetComponent(); HitComponent && HitComponent->IsSimulatingPhysics())
		{
			// Push loose physics objects (boxes, barrels...)
			HitComponent->AddImpulseAtLocation(Impulse * HitComponent->GetMass() * 0.01f, Hit.ImpactPoint);
		}
	}
}

#if !UE_BUILD_SHIPPING
void AOpenWorldCharacter::TickSelfTest(float DeltaSeconds)
{
	// Scripted check of the attack layer, run with: -game -OWSelfTest (works with -NullRHI).
	// Logs bone positions in the mesh's space so they can be compared with the generated animations.
	SelfTestTime += DeltaSeconds;
	USkeletalMeshComponent* Body = GetMesh();
	const UOpenWorldAnimInstance* AnimInstance = GetOverlayAnimInstance();

	const auto Bone = [Body](const TCHAR* Name) { return Body->GetSocketTransform(Name, RTS_Component).GetLocation(); };
	const auto LogPose = [&](const TCHAR* Phase)
	{
		if (SelfTestTime < SelfTestNextLog)
		{
			return;
		}
		SelfTestNextLog = SelfTestTime + 0.1f;
		const FVector HandR = Bone(TEXT("hand_r")), HandL = Bone(TEXT("hand_l")), Pelvis = Bone(TEXT("pelvis")), FootR = Bone(TEXT("foot_r"));
		const float Grips = FVector::Dist(Bone(TEXT("HandGrip_R")), Bone(TEXT("HandGrip_L")));
		UE_LOG(LogOpenWorld, Display, TEXT("OWSELFTEST %s overlay=%.2f attacking=%d speed=%.0f hand_r=(%.0f,%.0f,%.0f) hand_l=(%.0f,%.0f,%.0f) grips=%.1f pelvis=(%.0f,%.0f,%.0f) foot_r=(%.0f,%.0f,%.0f)"),
			Phase, AnimInstance ? AnimInstance->GetOverlayTime() : -1.f, bIsAttacking ? 1 : 0, GetVelocity().Size2D(),
			HandR.X, HandR.Y, HandR.Z, HandL.X, HandL.Y, HandL.Z, Grips, Pelvis.X, Pelvis.Y, Pelvis.Z, FootR.X, FootR.Y, FootR.Z);
	};
	const auto NextStep = [this]() { ++SelfTestStep; SelfTestNextLog = 0.f; };

	switch (SelfTestStep)
	{
	case 0:
		if (SelfTestTime >= 1.0f)
		{
			Body->VisibilityBasedAnimTickOption = EVisibilityBasedAnimTickOption::AlwaysTickPoseAndRefreshBones;
			UE_LOG(LogOpenWorld, Display, TEXT("OWSELFTEST anim_instance=%s loadouts=%d current=%d weapon=%s offhand=%s"),
				*GetNameSafe(Body->GetAnimInstance() ? Body->GetAnimInstance()->GetClass()->GetSuperClass() : nullptr), Loadouts.Num(), CurrentLoadoutIndex,
				*GetNameSafe(Weapon->GetStaticMesh()), *GetNameSafe(OffHandWeapon->GetStaticMesh()));
			NextStep();
		}
		break;
	case 1:
		LogPose(TEXT("idle"));
		if (SelfTestTime >= 1.5f) { Attack(); NextStep(); }
		break;
	case 2:
		LogPose(TEXT("stand_1h"));
		if (SelfTestTime >= 2.8f)
		{
			EquipNextLoadout();
			UE_LOG(LogOpenWorld, Display, TEXT("OWSELFTEST switched current=%d weapon=%s offhand=%s"), CurrentLoadoutIndex,
				*GetNameSafe(Weapon->GetStaticMesh()), *GetNameSafe(OffHandWeapon->GetStaticMesh()));
			NextStep();
		}
		break;
	case 3:
		if (SelfTestTime >= 3.0f) { Attack(); NextStep(); }
		break;
	case 4:
		LogPose(TEXT("stand_2h"));
		if (SelfTestTime >= 4.6f) { EquipNextLoadout(); NextStep(); }
		break;
	case 5:
		AddMovementInput(GetActorForwardVector(), 1.f);
		if (SelfTestTime >= 5.6f) { Attack(); NextStep(); }
		break;
	case 6:
		AddMovementInput(GetActorForwardVector(), 1.f);
		LogPose(TEXT("run_1h"));
		if (SelfTestTime >= 6.8f)
		{
			UE_LOG(LogOpenWorld, Display, TEXT("OWSELFTEST done"));
			NextStep();
			FPlatformMisc::RequestExit(false);
		}
		break;
	default:
		break;
	}
}
#endif

void AOpenWorldCharacter::UpdateRotationMode()
{
	// Right button held: the character turns to face where the camera looks (and A/D strafe).
	// Left button only: the camera orbits freely and the character keeps its own facing.
	const bool bFaceCamera = bCameraRotating;

	UCharacterMovementComponent* Movement = GetCharacterMovement();
	Movement->bOrientRotationToMovement = !bFaceCamera;
	Movement->bUseControllerDesiredRotation = bFaceCamera;
	Movement->RotationRate.Yaw = bFaceCamera ? FaceCameraRotationRate : DefaultRotationRateYaw;
}

void AOpenWorldCharacter::SetupPlayerInputComponent(UInputComponent* PlayerInputComponent)
{
	// Set up action bindings
	if (UEnhancedInputComponent* EnhancedInputComponent = Cast<UEnhancedInputComponent>(PlayerInputComponent)) {
		
		// Jumping
		EnhancedInputComponent->BindAction(JumpAction, ETriggerEvent::Started, this, &ACharacter::Jump);
		EnhancedInputComponent->BindAction(JumpAction, ETriggerEvent::Completed, this, &ACharacter::StopJumping);

		// Moving
		EnhancedInputComponent->BindAction(MoveAction, ETriggerEvent::Triggered, this, &AOpenWorldCharacter::Move);
		EnhancedInputComponent->BindAction(MouseLookAction, ETriggerEvent::Triggered, this, &AOpenWorldCharacter::MouseLook);

		// Looking (gamepad right stick, always active)
		EnhancedInputComponent->BindAction(LookAction, ETriggerEvent::Triggered, this, &AOpenWorldCharacter::Look);

		// MMO-style camera: wheel zoom, right button rotate, left button orbit
		SetupCameraInput();
		EnhancedInputComponent->BindAction(CameraZoomAction, ETriggerEvent::Triggered, this, &AOpenWorldCharacter::CameraZoom);
		EnhancedInputComponent->BindAction(CameraRotateAction, ETriggerEvent::Started, this, &AOpenWorldCharacter::CameraRotateStarted);
		EnhancedInputComponent->BindAction(CameraRotateAction, ETriggerEvent::Completed, this, &AOpenWorldCharacter::CameraRotateCompleted);
		EnhancedInputComponent->BindAction(CameraOrbitAction, ETriggerEvent::Started, this, &AOpenWorldCharacter::CameraOrbitStarted);
		EnhancedInputComponent->BindAction(CameraOrbitAction, ETriggerEvent::Completed, this, &AOpenWorldCharacter::CameraOrbitCompleted);

		// Sprint while Left Shift is held
		EnhancedInputComponent->BindAction(SprintAction, ETriggerEvent::Started, this, &AOpenWorldCharacter::SprintStarted);
		EnhancedInputComponent->BindAction(SprintAction, ETriggerEvent::Completed, this, &AOpenWorldCharacter::SprintCompleted);

		// Mouse wheel click: sword and shield <-> two-handed sword
		EnhancedInputComponent->BindAction(SwitchLoadoutAction, ETriggerEvent::Started, this, &AOpenWorldCharacter::EquipNextLoadout);
	}
	else
	{
		UE_LOG(LogOpenWorld, Error, TEXT("'%s' Failed to find an Enhanced Input component! This template is built to use the Enhanced Input system. If you intend to use the legacy system, then you will need to update this C++ file."), *GetNameSafe(this));
	}
}

void AOpenWorldCharacter::Move(const FInputActionValue& Value)
{
	// input is a Vector2D
	FVector2D MovementVector = Value.Get<FVector2D>();

	// route the input
	DoMove(MovementVector.X, MovementVector.Y);
}

void AOpenWorldCharacter::Look(const FInputActionValue& Value)
{
	// input is a Vector2D
	FVector2D LookAxisVector = Value.Get<FVector2D>();

	// route the input
	DoLook(LookAxisVector.X, LookAxisVector.Y);
}

void AOpenWorldCharacter::DoMove(float Right, float Forward)
{
	if (GetController() != nullptr)
	{
		// find out which way is forward
		const FRotator Rotation = GetController()->GetControlRotation();
		const FRotator YawRotation(0, Rotation.Yaw, 0);

		// get forward vector
		const FVector ForwardDirection = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::X);

		// get right vector 
		const FVector RightDirection = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::Y);

		// add movement 
		AddMovementInput(ForwardDirection, Forward);
		AddMovementInput(RightDirection, Right);
	}
}

void AOpenWorldCharacter::DoLook(float Yaw, float Pitch)
{
	if (GetController() != nullptr)
	{
		// add yaw and pitch input to controller
		AddControllerYawInput(Yaw);
		AddControllerPitchInput(Pitch);
	}
}

void AOpenWorldCharacter::DoJumpStart()
{
	// signal the character to jump
	Jump();
}

void AOpenWorldCharacter::DoJumpEnd()
{
	// signal the character to stop jumping
	StopJumping();
}
